chars = list(G.keys())
COLS = 16
rows = (len(chars) + COLS - 1) // COLS
img = Image.new("RGBA", (COLS * 6, rows * 10), (0, 0, 0, 0))
px = img.load()
for i, ch in enumerate(chars):
    cx, cy = (i % COLS) * 6, (i // COLS) * 10
    for r, line in enumerate(G[ch]):
        assert len(line) == 5, (ch, line)
        for c, v in enumerate(line):
            if v == "#":
                px[cx + c, cy + 1 + r] = (255, 255, 255, 255)
img.save(sys.argv[1])
# character list for the Godot image-font importer (ranges as decimal code points)
print(",".join(str(ord(c)) for c in chars))
print(len(chars), COLS, rows)
